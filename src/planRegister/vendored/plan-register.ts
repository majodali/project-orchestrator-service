// ---- The stage vocabulary, as data ---------------------------------
//
// Cited to docs/process/plan-model.md, "The node lifecycle" table.
// Order matches that table. Carried here as data only: this module
// does not check a parsed node's stage against this list (D5 — "no
// policy in the unit").

export const STAGES = [
  "identified",
  "planned",
  "specified",
  "broken-down",
  "executing",
  "verifying",
  "done",
] as const;

export type Stage = (typeof STAGES)[number];

// ---- Structured shape -----------------------------------------------
//
// Cited to docs/process/plan-register.md, "Entry anatomy".

export interface HoldMarker {
  kind: "gated" | "blocked";
  reason: string;
}

/** A `label: target` pair parsed out of a node's post-em-dash text. */
export interface RegisterLink {
  label: string;
  target: string;
}

export interface PlanNode {
  id: string;
  /**
   * The stage string exactly as written in the register. Not
   * validated against `STAGES` here — see the module doc comment
   * (D5, "nothing is guarded that is not shared").
   */
  stage: string;
  hold: HoldMarker | null;
  title: string;
  /**
   * Verbatim text after the entry's em dash, if any — kept in full
   * even when it does not fit the `label: target` link grammar (the
   * live register's P1-N006 line carries plain prose there instead
   * of a link). `links` below is a best-effort structured read of
   * this same text.
   */
  annotation: string | null;
  links: RegisterLink[];
  parentId: string | null;
  /** Document order, not creation order (register nodes are never
   * reordered by this parser). */
  childIds: string[];
  /** 1-based line number in the source register text. */
  line: number;
}

/**
 * A register line that looked like it was trying to be a node entry
 * (matched the node-*like* shape) but did not parse as one, or a
 * structural problem (a duplicate ID) discovered while parsing one
 * that did. Always reported, never silently dropped.
 */
export interface RegisterParseError {
  line: number;
  /** The literal source line, untouched. */
  raw: string;
  reason: string;
}

export interface RegisterParseResult {
  nodes: Map<string, PlanNode>;
  /** Node IDs in document (source-line) order. */
  order: string[];
  /** IDs of nodes with no parent — the register's top-level entries. */
  rootIds: string[];
  errors: RegisterParseError[];
}

// ---- Grammar ----------------------------------------------------------
//
// Entry anatomy: indent, "- ", node ID, "[stage]", optional
// "[gated: ...]"/"[blocked: ...]", then the rest of the line (name,
// optionally " — " + links). Named groups, with the shape asserted
// explicitly below rather than left to regex-literal inference: TS's
// inference for `groups` does not track per-group optionality
// precisely enough here to satisfy noUncheckedIndexedAccess cleanly.

const NODE_LINE =
  /^(?<indent>\s*)- (?<id>P\d+-N\d+) \[(?<stage>[a-z-]+)\](?: \[(?<holdKind>gated|blocked): (?<holdReason>[^\]]+)\])? (?<rest>.*)$/;

interface NodeLineGroups {
  indent: string;
  id: string;
  stage: string;
  holdKind: "gated" | "blocked" | undefined;
  holdReason: string | undefined;
  rest: string;
}

// A list-item line that is either a well-formed node ID, or carries
// *some* stage-shaped bracket — i.e. it is plausibly attempting to be
// a node entry, so a failure to match NODE_LINE below is reported
// rather than silently skipped as ordinary register prose.
const NODE_LIKE_LINE = /^\s*- (?:P\d+-N\d+\b|[^\s].*\[[a-z-]+\])/;

const EM_DASH_SEPARATOR = " — ";
const LINK_SEPARATOR = " · ";
const LINK_PAIR = /^(?<label>[^:]+): (?<target>.+)$/;

interface LinkPairGroups {
  label: string;
  target: string;
}

function splitTitleAndAnnotation(rest: string): {
  title: string;
  annotation: string | null;
  links: RegisterLink[];
} {
  const idx = rest.indexOf(EM_DASH_SEPARATOR);
  if (idx === -1) {
    return { title: rest.trim(), annotation: null, links: [] };
  }
  const title = rest.slice(0, idx).trim();
  const annotation = rest.slice(idx + EM_DASH_SEPARATOR.length).trim();
  const links: RegisterLink[] = [];
  for (const segment of annotation.split(LINK_SEPARATOR)) {
    const m = LINK_PAIR.exec(segment.trim());
    if (m?.groups) {
      const groups = m.groups as unknown as LinkPairGroups;
      links.push({
        label: groups.label.trim(),
        target: groups.target.trim(),
      });
    }
  }
  return { title, annotation, links };
}

/**
 * Parses register text into structured nodes. Never throws on
 * malformed input: a node-like line that does not parse, or a
 * duplicate node ID, is recorded in `errors` (naming the line and the
 * problem) and parsing continues — every other, well-formed node is
 * still returned.
 */
export function parseRegister(text: string): RegisterParseResult {
  const nodes = new Map<string, PlanNode>();
  const order: string[] = [];
  const rootIds: string[] = [];
  const errors: RegisterParseError[] = [];
  const stack: Array<{ depth: number; id: string }> = [];

  const lines = text.split(/\r\n|\n/);
  for (const [i, line] of lines.entries()) {
    const lineno = i + 1;

    if (!NODE_LIKE_LINE.test(line)) {
      continue; // ordinary register prose — never a node, never an error
    }

    const m = NODE_LINE.exec(line);
    if (!m?.groups) {
      errors.push({
        line: lineno,
        raw: line,
        reason:
          "node-like line does not match the register grammar " +
          "(docs/process/plan-register.md)",
      });
      continue;
    }

    const { indent, id, stage, holdKind, holdReason, rest } =
      m.groups as unknown as NodeLineGroups;
    const depth = indent.length;

    if (nodes.has(id)) {
      errors.push({
        line: lineno,
        raw: line,
        reason: `duplicate node ID ${id}; first seen at line ${nodes.get(id)!.line}`,
      });
      continue;
    }

    while (stack.length > 0 && stack[stack.length - 1]!.depth >= depth) {
      stack.pop();
    }
    const parentId = stack.length > 0 ? stack[stack.length - 1]!.id : null;

    // holdReason is always present when holdKind is (they come from
    // the same optional regex group), so the non-null assertion here
    // is sound, not a bypass.
    const hold: HoldMarker | null =
      holdKind === "gated" || holdKind === "blocked"
        ? { kind: holdKind, reason: holdReason!.trim() }
        : null;

    const { title, annotation, links } = splitTitleAndAnnotation(rest);

    const node: PlanNode = {
      id,
      stage,
      hold,
      title,
      annotation,
      links,
      parentId,
      childIds: [],
      line: lineno,
    };

    nodes.set(id, node);
    order.push(id);
    if (parentId) {
      nodes.get(parentId)!.childIds.push(id);
    } else {
      rootIds.push(id);
    }
    stack.push({ depth, id });
  }

  return { nodes, order, rootIds, errors };
}

/**
 * IDs of `nodeId` and every descendant, in document (pre-order) order
 * — "that node and its descendants, nothing above, nothing sideways."
 * Returns `null` if `nodeId` is not in the parsed register at all.
 */
export function subtreeIds(
  result: RegisterParseResult,
  nodeId: string,
): string[] | null {
  if (!result.nodes.has(nodeId)) {
    return null;
  }
  const out: string[] = [];
  const visit = (id: string): void => {
    out.push(id);
    for (const childId of result.nodes.get(id)!.childIds) {
      visit(childId);
    }
  };
  visit(nodeId);
  return out;
}
