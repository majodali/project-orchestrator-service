/** Cells in a Cost log row: date, task, node, stage, role, model,
 * input tokens, output tokens, notes (docs/process/cost-log.md). */
export const COST_LOG_CELL_COUNT = 9;

/** A Cost log task ID (docs/process/cost-log.md). */
export const TASK_ID = /^T\d{3,}$/;

/** The run journal's event kinds (docs/process/observability.md). */
export const JOURNAL_EVENT_KINDS: ReadonlySet<string> = new Set([
  "dispatched",
  "result-received",
  "accepted",
  "check-failed",
  "needs-judgment",
  "blocked",
  "stale",
  "backward-transition",
  "packet-widened",
  "precedent-applied",
  "gate-opened",
  "gate-crossed",
  "sequence-ratified",
  "sequence-stopped",
  "edge-recorded",
]);

// ---- Cost log -------------------------------------------------------------

/** Splits one Markdown table line into its trimmed cells, dropping the
 * leading and trailing pipes. */
export function splitCostLogRow(row: string): string[] {
  return row
    .trim()
    .replace(/^\|+/, "")
    .replace(/\|+$/, "")
    .split("|")
    .map((c) => c.trim());
}

export type CostLogRowKind = "header" | "separator" | "data";

export interface CostLogTableRow {
  /** 1-based position among the file's table lines (the lines that
   * start with `|`), the number the form checker's findings cite. */
  position: number;
  /** 1-based line number in the file. */
  line: number;
  kind: CostLogRowKind;
  cells: string[];
}

/**
 * Every table line of a Cost log, in file order. The first table line
 * is the header. A line whose cells hold only `-`, `:` and spaces is a
 * separator (an all-empty row matches too). Every other table line is
 * a data row, whatever its cell count or task ID: checking those is
 * the reader's policy.
 */
export function costLogTableRows(text: string): CostLogTableRow[] {
  const rows: CostLogTableRow[] = [];
  const lines = text.split(/\r\n|\n/);
  let position = 0;
  for (let i = 0; i < lines.length; i++) {
    const raw = lines[i]!;
    if (!raw.startsWith("|")) continue;
    position += 1;
    const cells = splitCostLogRow(raw);
    let kind: CostLogRowKind;
    if (position === 1) {
      kind = "header";
    } else if (
      [...cells.join("")].every((ch) => ch === "-" || ch === " " || ch === ":")
    ) {
      kind = "separator";
    } else {
      kind = "data";
    }
    rows.push({ position, line: i + 1, kind, cells });
  }
  return rows;
}

// ---- Run journal ----------------------------------------------------------

/** One parsed journal line. Fields beyond `ts` and `event` are kept
 * as written. */
export interface JournalEvent {
  [key: string]: unknown;
}

export type JournalLine =
  | { line: number; status: "event"; event: JournalEvent }
  | { line: number; status: "invalid-json"; error: string }
  | { line: number; status: "missing-field" }
  | { line: number; status: "unknown-kind"; event: JournalEvent };

/**
 * Every non-blank line of a run journal, in file order, each with its
 * 1-based line number and what it is. A line is an event when it is a
 * JSON object carrying `ts` and `event`, and its `event` is one of
 * `JOURNAL_EVENT_KINDS`. A JSON value that is not an object carries no
 * field, so it reads as missing `ts` and `event`.
 */
export function journalLines(text: string): JournalLine[] {
  const out: JournalLine[] = [];
  const lines = text.split(/\r\n|\n/);
  for (let i = 0; i < lines.length; i++) {
    const line = i + 1;
    const raw = lines[i]!;
    if (raw.trim() === "") continue;
    let value: unknown;
    try {
      value = JSON.parse(raw);
    } catch (exc) {
      out.push({
        line,
        status: "invalid-json",
        error: exc instanceof Error ? exc.message : String(exc),
      });
      continue;
    }
    if (
      typeof value !== "object" ||
      value === null ||
      Array.isArray(value) ||
      !("ts" in value) ||
      !("event" in value)
    ) {
      out.push({ line, status: "missing-field" });
      continue;
    }
    const event = value as JournalEvent;
    if (!JOURNAL_EVENT_KINDS.has(String(event["event"]))) {
      out.push({ line, status: "unknown-kind", event });
      continue;
    }
    out.push({ line, status: "event", event });
  }
  return out;
}
