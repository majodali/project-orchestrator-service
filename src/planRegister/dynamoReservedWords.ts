/**
 * DynamoDB's reserved words (node P2-N010 rework, T027): an attribute
 * name that collides with one of these must be aliased through
 * `ExpressionAttributeNames` in any expression string — a
 * `ConditionExpression`, `KeyConditionExpression`, `ProjectionExpression`,
 * `UpdateExpression`, or `FilterExpression` — or DynamoDB rejects the
 * request at call time with "Attribute name is a reserved keyword".
 * That is exactly the shape of the production defect this module
 * exists to catch before a real table ever sees the request: `token`
 * in `dynamoLeaseBackend.ts`'s `releaseLease`, found on the first
 * production call ever made against the lease table.
 *
 * PARTIAL, DECLARED, NOT A FRESH FETCH: this session had no network
 * access to AWS's own "Reserved Words in DynamoDB" documentation page
 * (the environment's outbound access is limited to a small
 * package-registry allowlist; a direct request to
 * docs.aws.amazon.com was rejected by the proxy). A search of the npm
 * registry for a package that could supply the list turned up
 * `@dynotable/dynamodb-reserved-words`, claiming to be "the complete
 * list of 573 DynamoDB reserved words" — published by a brand-new,
 * unfamiliar maintainer with no other packages, days before this
 * task, and matching this exact need suspiciously precisely. This
 * session declined to install it: an unverifiable dependency that
 * appears right when an agent goes looking for one is a supply-chain
 * risk worth naming and avoiding, not a shortcut worth taking, and
 * that judgment call is reported rather than silently acted on.
 *
 * What follows instead is this session's own reconstruction of AWS's
 * published list, assembled from training-time familiarity with it
 * (it is widely reproduced verbatim in AWS's own docs and elsewhere)
 * rather than a live fetch — believed close to complete, but its
 * completeness could not be verified against the authoritative source
 * this session. Treat an absence from this list as weak evidence of
 * safety, not proof: this module is maintained to have no *false
 * positives* (nothing on it is safe to use bare in an expression) but
 * may have false negatives (a real reserved word this session did not
 * recall or mis-typed). Cross-check any name this module does not
 * flag against AWS's own page before trusting it in a newly written
 * expression, and prefer aliasing every attribute name through
 * `ExpressionAttributeNames` unconditionally if that check is ever
 * skipped — it is always correct, reserved or not.
 */

